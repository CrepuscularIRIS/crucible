#!/usr/bin/env python3
"""Stage one ResearchClawBench task into a workspace OUTSIDE the RCB repo
(plan 05 §3.1-§3.2, slice S3).

    python3 research/bench/stage_rcb.py Information_005 <workspace> [--rcb-root DIR]

Copies only data/ and related_work/, writes task-card.yaml from task_info.json's
public fields (task, data) and MANIFEST.sha256, and creates the upstream working
dirs (code/ outputs/ report/images/). Never reads into target_study/ except to
hash it: if any staged file is byte-identical to a target_study file, the
workspace is deleted and staging fails.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

import yaml

from _tree import require_empty, sha256_file, write_sha_manifest

DEFAULT_RCB_ROOT = Path.home() / "oss" / "ResearchClawBench"
PUBLIC_DIRS = ("data", "related_work")
PUBLIC_INFO_KEYS = ("task", "data")
WORK_DIRS = ("code", "outputs", "report/images")

# Upstream instructions_tmpl.py "Deliverables", minus "install packages as needed".
DELIVERABLES = {
    "code/": "analysis code",
    "outputs/": "intermediate results",
    "report/report.md": "methodology, results and discussion; figures referenced as images/<name>.png",
    "report/images/": "every figure, PNG only, generated by a script in code/",
}


def _shas(root: Path) -> dict[str, Path]:
    return {sha256_file(p): p for p in root.rglob("*") if p.is_file()} if root.is_dir() else {}


def stage(task_id: str, out_dir: Path, rcb_root: Path = DEFAULT_RCB_ROOT) -> Path:
    task_dir = rcb_root / "tasks" / task_id
    info = json.loads((task_dir / "task_info.json").read_text(encoding="utf-8"))
    if not (task_dir / "target_study").is_dir():
        raise ValueError(f"{task_id} has no target_study/; the leak check below would be vacuous")
    if out_dir.resolve().is_relative_to(rcb_root.resolve()):
        raise ValueError(f"workspace {out_dir} is inside the RCB repo; ../../tasks/*/target_study would be reachable")
    require_empty(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    try:
        for name in PUBLIC_DIRS:
            if (task_dir / name).is_dir():
                shutil.copytree(task_dir / name, out_dir / name)  # symlinks are followed -> hashed below
        truth = _shas(task_dir / "target_study")
        clashes = sorted(str(p.relative_to(out_dir)) for sha, p in _shas(out_dir).items() if sha in truth)
        if clashes:
            raise ValueError(f"public inputs duplicate target_study files: {clashes}")
    except BaseException:
        shutil.rmtree(out_dir, ignore_errors=True)
        raise

    card = {"id": task_id, **{k: info[k] for k in PUBLIC_INFO_KEYS if k in info}, "deliverables": DELIVERABLES}
    (out_dir / "task-card.yaml").write_text(
        yaml.safe_dump(card, allow_unicode=True, sort_keys=False, width=100), encoding="utf-8")
    for entry in info.get("data") or []:
        rel = str(entry.get("path", "")).removeprefix("./")
        if rel and not (out_dir / rel).exists():
            print(f"stage_rcb: task_info lists {rel!r} but it is not in data/ (upstream inconsistency)", file=sys.stderr)
    write_sha_manifest(out_dir)
    for d in WORK_DIRS:
        (out_dir / d).mkdir(parents=True, exist_ok=True)
    return out_dir


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("task_id")
    ap.add_argument("workspace", type=Path)
    ap.add_argument("--rcb-root", type=Path, default=DEFAULT_RCB_ROOT)
    args = ap.parse_args(argv)
    out = stage(args.task_id, args.workspace, args.rcb_root)
    print(f"staged {args.task_id} -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
