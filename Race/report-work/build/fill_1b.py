def set_para(para, text: str, size: float | None = None, bold: bool | None = None):
    """替换段落文本,保留第一个 run 的样式。"""
    runs = para.runs
    if not runs:
        para.add_run(text)
        runs = para.runs
    runs[0].text = text
    for r in runs[1:]:
        r.text = ""
    if size is not None:
        for r in runs:
            r.font.size = Pt(size)
    if bold is not None:
        for r in runs:
            r.font.bold = bold


def fill_cell(cell, text: str, size: float = 9):
    cell.text = ""
    p = cell.paragraphs[0]
    run = p.add_run(text)
    run.font.size = Pt(size)
    # 中文字号
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = rPr.makeelement(qn("w:rFonts"), {})
        rPr.append(rFonts)
    for a in ("w:ascii", "w:hAnsi", "w:eastAsia"):
        rFonts.set(qn(a), "宋体")


